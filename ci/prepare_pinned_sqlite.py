#!/usr/bin/env python3
"""Verify and materialize the exact official SQLite amalgamation for Android NDK."""

from __future__ import annotations

import argparse
import hashlib
import io
import re
import zipfile
from pathlib import Path

SQLITE_VERSION = "3.54.1"
SQLITE_VERSION_NUMBER = "3054001"
SQLITE_SOURCE_ID = (
    "2026-10-16 14:45:20 "
    "555e07ef33f69a0957d24d8e555b702464a131d6f1607f4c3c1e4551e8e6ca76"
)
ARCHIVE_SHA3_256 = (
    "92281c86e2957f9b9305890f9ac04204caa7b677cc868dc326d942689df28e30"
)
ARCHIVE_MEMBERS = (
    "sqlite-amalgamation-3540100/sqlite3.c",
    "sqlite-amalgamation-3540100/sqlite3.h",
)


def verify_archive_digest(payload: bytes, expected: str = ARCHIVE_SHA3_256) -> bool:
    actual = hashlib.sha3_256(payload).hexdigest()
    if actual != expected:
        raise ValueError(f"SQLite archive SHA3-256 mismatch: {actual}")
    return True


def extract_and_pin(payload: bytes, vendor_dir: Path, pin_file: Path) -> dict[str, str]:
    with zipfile.ZipFile(io.BytesIO(payload)) as archive:
        names = set(archive.namelist())
        if not set(ARCHIVE_MEMBERS).issubset(names):
            raise ValueError("Pinned SQLite archive is missing sqlite3.c or sqlite3.h")
        sqlite_c = archive.read(ARCHIVE_MEMBERS[0])
        sqlite_h = archive.read(ARCHIVE_MEMBERS[1])

    version_match = re.search(rb'^#define SQLITE_VERSION_NUMBER[ \\t]+([0-9]+)', sqlite_h, re.MULTILINE)
    source_match = re.search(rb'^#define SQLITE_SOURCE_ID "([^"]+)"', sqlite_c, re.MULTILINE)
    if version_match is None or version_match.group(1).decode() != SQLITE_VERSION_NUMBER:
        raise ValueError("SQLite amalgamation version number does not match the approved pin")
    if source_match is None or source_match.group(1).decode() != SQLITE_SOURCE_ID:
        raise ValueError("SQLite amalgamation source ID does not match the approved pin")

    hashes = {
        "c": hashlib.sha256(sqlite_c).hexdigest(),
        "h": hashlib.sha256(sqlite_h).hexdigest(),
    }
    vendor_dir.mkdir(parents=True, exist_ok=True)
    pin_file.parent.mkdir(parents=True, exist_ok=True)
    (vendor_dir / "sqlite3.c").write_bytes(sqlite_c)
    (vendor_dir / "sqlite3.h").write_bytes(sqlite_h)
    pin_file.write_text(
        "# Generated by ci/prepare_pinned_sqlite.py; do not edit.\n"
        f'set(SQLITE_EXPECTED_VERSION_NUMBER "{SQLITE_VERSION_NUMBER}")\\n'
        f'set(SQLITE_EXPECTED_SOURCE_ID "{SQLITE_SOURCE_ID}")\\n'
        f'set(SQLITE_EXPECTED_C_SHA256 "{hashes["c"]}")\\n'
        f'set(SQLITE_EXPECTED_H_SHA256 "{hashes["h"]}")\\n'
        f'set(SQLITE_EXPECTED_ARCHIVE_SHA3_256 "{ARCHIVE_SHA3_256}")\\n',
        encoding="utf-8",
    )
    return hashes


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--archive", required=True, type=Path)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    payload = args.archive.read_bytes()
    if len(payload) > 5 * 1024 * 1024:
        raise ValueError("SQLite archive exceeded the 5 MiB safety limit")
    verify_archive_digest(payload)
    vendor = args.root / "android-app/app/build/generated/sqlite/vendor"
    pins = args.root / "android-app/app/build/generated/sqlite/sqlite3-pins.cmake"
    hashes = extract_and_pin(payload, vendor, pins)
    print(f"SQLITE_VERSION={SQLITE_VERSION}")
    print(f"SQLITE_VERSION_NUMBER={SQLITE_VERSION_NUMBER}")
    print(f"SQLITE_SOURCE_ID={SQLITE_SOURCE_ID}")
    print(f"SQLITE_ARCHIVE_SHA3_256={ARCHIVE_SHA3_256}")
    print(f"SQLITE3_C_SHA256={hashes['c']}")
    print(f"SQLITE3_H_SHA256={hashes['h']}")
    print("PINNED_SQLITE_PREPARATION=PASS")


if __name__ == "__main__":
    main()
